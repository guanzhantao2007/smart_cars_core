void HAL_TIM_PeriodElapsedCallback(TIM_HandleTypeDef *htim)
{
  if (htim->Instance == TIM6)
  {
    IMU_Tick1ms();
  }
  else if (htim->Instance == TIM7)
  {
    /* TIM7 = 84 MHz / 84 / 10000 = 100 Hz，即 10 ms 一拍。
     * 先推进编码器时基，再跑 PID：这样 PID 看到的 elapsed_ticks 恒为 1，
     * 控制周期和测速窗口严格对齐。 */
    encoder_timebase_tick();

    /* T09 接线：角度环先跑一拍（采 yaw + 算 ω），PidTune 末尾的波形块
     * 随后读同一拍样本 —— 顺序不可反。放在 PidTune 之后就变成读上一拍的
     * yaw，同一帧里 CH9 与 CH13 差 10 ms，看着像 IMU 抖动。
     * 本函数只算、只存，不驱动任何电机。 */
    YawLoop_Tick();

    PidTune_Tick10ms();
  }
}

void HAL_UART_ErrorCallback(UART_HandleTypeDef *huart)
{
  if (huart->Instance == USART1)
  {
    Task1_UartError();
  }
  else if (huart->Instance == USART2)
  {
    /* 调参串口溢出：必须重挂接收，否则从此收不到命令（不报错、不提示） */
    Serial_RxRecover();
  }
}

