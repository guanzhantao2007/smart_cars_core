  hi2c1.Instance = I2C1;
  /* 【2026-11-22 20:40 改回】400 kHz -> 100 kHz，用于排查 IMU 完全不应答。
   *
   * 为什么先降速：模块经**排母**插在 PCB 上，实测上电灯亮但 I2C 全无 ACK
   *   （iscan found 0）。400 kHz 对排母接触电阻、寄生电容、上拉强弱都更敏感，
   *   先退到 100 kHz 排掉"速度太快"这个变量，是最便宜的一步。
   *
   * 代价（已核对代码，不是估的）：IMU 每拍读 14 字节，100 kHz 下约 1.4 ms，
   *   比 TIM6 的 1.06 ms 采样周期长 ⇒ IMU_Update 实际约 700 Hz 而不是 940 Hz。
   *   **但这不会把 yaw 积分拉偏**：imu.c 的积分用的是 s_tick 的差值
   *   （dt_ticks），不是固定 dt，采样变稀只影响分辨率，不产生系统性偏差。
   *   （P0 那版注释写"会被系统性拉偏"，这一句是错的，已一并改掉。）
   *
   * DutyCycle 在 100 kHz 下无意义（标准模式），保持 2:1 不影响。
   * 同步改了 smart_cars.ioc（I2C1.ClockSpeed=100000），否则 CubeMX 重新
   *   生成代码会把这里刷回 400000。 */
  hi2c1.Init.ClockSpeed = 100000;
  hi2c1.Init.DutyCycle = I2C_DUTYCYCLE_2;
  hi2c1.Init.OwnAddress1 = 0;
  hi2c1.Init.AddressingMode = I2C_ADDRESSINGMODE_7BIT;
  hi2c1.Init.DualAddressMode = I2C_DUALADDRESS_DISABLE;
  hi2c1.Init.OwnAddress2 = 0;
  hi2c1.Init.GeneralCallMode = I2C_GENERALCALL_DISABLE;
  hi2c1.Init.NoStretchMode = I2C_NOSTRETCH_DISABLE;
  if (HAL_I2C_Init(&hi2c1) != HAL_OK)
  {
    Error_Handler();
  }
