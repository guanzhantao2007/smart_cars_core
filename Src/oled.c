/* 设置显存页和列地址。 */
static HAL_StatusTypeDef OLED_SetPage(uint8_t page)
{
    uint16_t col = OLED_COLUMN_OFFSET;
    uint8_t cmd[4] = {
        0x00U,
        (uint8_t)(0xB0U | page),
        (uint8_t)(0x10U | ((col >> 4) & 0x0FU)),
        (uint8_t)(col & 0x0FU)
    };
    return HAL_I2C_Master_Transmit(oled_i2c, OLED_I2C_WRITE_ADDR,
                                   cmd, sizeof(cmd), OLED_I2C_TIMEOUT_MS);
}

/* 按页发送显存数据到 OLED。 */
HAL_StatusTypeDef OLED_Update(void)
{
    uint8_t packet[OLED_W + 1U];
    uint8_t page;
    HAL_StatusTypeDef status;

    if (oled_i2c == NULL)
        return HAL_ERROR;

    packet[0] = 0x40U; 
    for (page = 0; page < (OLED_H / 8U); page++)
    {
        status = OLED_SetPage(page);
        if (status != HAL_OK)
            return status;

        memcpy(&packet[1], framebuffer[page], OLED_W);
        status = HAL_I2C_Master_Transmit(oled_i2c, OLED_I2C_WRITE_ADDR,
                                         packet, sizeof(packet), OLED_I2C_TIMEOUT_MS);
        if (status != HAL_OK)
            return status;
    }
    return HAL_OK;
}

/* 清空软件显存。 */
void OLED_Clear(void)
{
    memset(framebuffer, 0, sizeof(framebuffer));
}

/* 初始化 SSD1306 并清屏。 */
HAL_StatusTypeDef OLED_Init(I2C_HandleTypeDef *hi2c)
{

    uint8_t init_cmd[] = {
        0x00U, 0xAEU, 0xD5U, 0x80U, 0xA8U, 0x3FU,
        0xD3U, 0x00U, 0x40U, 0xA1U, 0xC8U,
        0xDAU, 0x12U, 0x81U, 0xCFU, 0xD9U, 0xF1U,
        0xDBU, 0x30U, 0xA4U, 0xA6U, 0x8DU, 0x14U,
        0x20U, 0x02U, 0xAFU
    };
    HAL_StatusTypeDef status;

    if (hi2c == NULL)
        return HAL_ERROR;
    oled_i2c = hi2c;
    HAL_Delay(100U); 
    status = HAL_I2C_Master_Transmit(oled_i2c, OLED_I2C_WRITE_ADDR,
                                     init_cmd, sizeof(init_cmd), OLED_I2C_TIMEOUT_MS);
    if (status != HAL_OK)
        return status;
    OLED_Clear();
    return OLED_Update();
}

/* 修改显存中的单个像素。 */
static void OLED_PutPixel(int32_t x, int32_t y, uint8_t on)
{
    uint8_t mask;
    if (x < 0 || x >= OLED_W || y < 0 || y >= OLED_H)
        return;
    mask = (uint8_t)(1U << ((uint32_t)y & 7U));
    if (on)
        framebuffer[(uint32_t)y / 8U][(uint32_t)x] |= mask;
    else
        framebuffer[(uint32_t)y / 8U][(uint32_t)x] &= (uint8_t)~mask;
}

/* 在显存中绘制一个 ASCII 字符。 */
void OLED_ShowChar(int16_t x, int16_t y, char ch, uint8_t font)
{
    uint8_t width, height, i, j, value;
    uint8_t index;

    if (font != OLED_6X8 && font != OLED_8X16)
        return;
    if ((uint8_t)ch < 32U || (uint8_t)ch > 126U)
        ch = '?';

    index = (uint8_t)ch - 32U;
    width  = font;
    height = (font == OLED_6X8) ? 8U : 16U;

    for (i = 0; i < width; ++i)
    {
        for (j = 0; j < height; ++j)
        {
            if (font == OLED_6X8)
                value = (uint8_t)((font6x8[index][i] >> j) & 1U);
            else
                value = (uint8_t)((font8x16[index][i + (j / 8U) * 8U]
                                  >> (j & 7U)) & 1U);
            OLED_PutPixel((int32_t)x + i, (int32_t)y + j, value);
        }
    }
}

/* 在显存中绘制字符串。 */
void OLED_ShowString(int16_t x, int16_t y, const char *str, uint8_t font)
{
    int32_t cursor_x = x;
    int32_t cursor_y = y;
    uint8_t height;

    if (str == NULL || (font != OLED_6X8 && font != OLED_8X16))
        return;
    height = (font == OLED_6X8) ? 8U : 16U;
    while (*str != '\0' && cursor_y < OLED_H)
    {
        if (*str == '\n')
        {
            cursor_y += height;
            cursor_x = x;
        }
        else
        {
            if (cursor_x >= OLED_W)
                break; 
            OLED_ShowChar((int16_t)cursor_x, (int16_t)cursor_y, *str, font);
            cursor_x += font;
        }
        ++str;
    }
}

/* 按指定宽度绘制十进制整数。 */
void OLED_ShowNum(int16_t x, int16_t y, uint32_t number,
                  uint8_t length, uint8_t font)
{
    char digits[11];
    uint8_t i;
    if (length == 0U || length > 10U)
        return;
    digits[length] = '\0';
    for (i = length; i > 0U; --i)
    {
        digits[i - 1U] = (char)('0' + number % 10U);
        number /= 10U;
    }
    OLED_ShowString(x, y, digits, font);
}
