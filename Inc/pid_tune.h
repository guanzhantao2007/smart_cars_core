#ifndef __PID_TUNE_H
#define __PID_TUNE_H

#include <stdint.h>

/* ============================================================================
 * 四电机 PID 在线调参（VOFA+ 文本协议）
 *
 * 移植自 samll_car_vofa_bak_20261113_A（STM32F103 两轮小车，已实操验证）：
 *   pid.c      PID 运算本体            —— 原样
 *   pidcmd.c   下行命令解析            —— 原样
 *   vofa.c     上行波形拼帧            —— 原样 + 一位小数版本
 *   serial_async.c  串口异步收发        —— 按 F4 的 HAL 重写
 *   本文件     四电机适配层            —— 单位/轮数/周期不同，必须重写
 *
 * ---- 命令一览（一行一条，VOFA 滑块的默认格式就是「控件名:数值」）----
 *   kp 0.5 / ki 0.02 / kd 0     改「当前 ch」这一组的单个增益
 *   kp3 0.6                     带编号，直接写 3 号电机，不用先切 ch
 *   pid 0.5 0.02 0              一次设全三个（当前 ch）
 *   ?                           回读： #KP=.. KI=.. KD=.. TGT=.. CHx RUN/STOP
 *   ch 3 / ch3                  切到 3 号电机（1~4）。切换后 kp/ki/kd 改的就是它
 *                               （ch3 连写是给 VOFA 按钮用的，两种写法等价）
 *   tgt 500                     当前 ch 的目标线速度，**mm/s，物理真值**，可负
 *                               ⇒ 每发一次都清积分，适合"敲一次"
 *   t 500                       当前 ch 的目标，**mm/s**，可负
 *                               ⇒ 【滑块专用】不清积分 + 其余三路目标清零
 *                                  调 Ki 必须用它，理由见 pid_tune.c 里的注释
 *   all 500                     四个轮子同速，验直线用
 *   o 25                        开环自检：当前 ch 直接给 **25% 占空比**（不过 PID）
 *   o 0                         退出开环并停车
 *   run / stop                  启停。stop = 目标清零 + PWM 归零 + 清积分
 *   zero                        当前 ch 三个增益清零（安全阀）
 *
 * ---- VOFA+ 滑块怎么配（一套滑块 + 切通道按钮，2026-11-22 定）----
 *   命令（左侧命令栏新建，Str/Ascii 模式；末尾换行按 VOFA 默认发送，
 *         真要是不带换行，固件还有一层 15 ms 半行兜底，一样收得到）：
 *     kp:%f      → 绑 Kp 滑块   from 0  to 3.0   step 0.05
 *     ki:%f      → 绑 Ki 滑块   from 0  to 0.5   step 0.005
 *     t:%f       → 绑目标滑块   from -1657 to 1657  step 10
 *     ch1/ch2/ch3/ch4 → 四个按钮，点了切通道；名称建议写「调1号」
 *     stop / zero     → 两个急停按钮，建议常驻
 *   %f 是 VOFA 命令的占位符，拖滑块时被替换成当前浮点值后整条发下去
 *   （官方文档「数据、命令、参数」：命令 hello:%f 会发出 "hello:1\n"）。
 *   切通道后 Kp/Ki/目标三个滑块立刻作用在新通道上，滑块本身不用改。
 *   波形 CH0 显示的就是当前 ch 的目标，拖滑块时看它有没有跟着动即可确认链路通。
 *
 * ---- 量纲（2026-11-22 改，务必看清）----
 *   tgt / t / all / 波形纵轴 = mm/s，满量程实测 1657 mm/s（100% 占空比、空载）
 *   o / 增益 / PID 输出   = 占空比百分比，0~100
 *
 *   ⇒ **tgt 给 30 现在真的只有 30 mm/s**（≈1.8% 占空比，在死区里，轮子不转）。
 *     旧版 FULL_SCALE=100 时 tgt 30 其实是 30% 占空比 ≈ 500 mm/s —— 同一个
 *     数字的物理含义变了，这是这次修"标签骗人"的代价。
 *     起步建议 tgt 300~600（18~36% 占空比，已经跑起来了）。
 *
 * ---- 波形（5 列，50 Hz，文本，纵轴是 0.1 mm/s）----
 *   CH0 = 当前 ch 的指令（开环时是 `o` 换算过去的等效 mm/s）
 *   CH1~CH4 = 电机1~4 的实测速度（正值 = 车头方向）
 *   图上读数 3050 就是 305.0 mm/s。
 *
 * ---- 两个前提，缺一个就动不了 ----
 *   1. 先发 ch / kp / ki / kd 把参数给进去（上电是保守默认值，不是 0）
 *   2. 先发 o 命令确认四轮转向和编码器符号都对，再上闭环
 *      （2026-11-22 已按实测把四台编码器符号和右后的 PWM 极性修好，
 *        见 motor.c 的 motor_mount_reverse、encoder.c 的 forward_count_sign）
 * ========================================================================= */

/**
  * @brief  初始化调参模块（串口、四组 PID、默认增益）
  * @note   必须在 Task_Init() 之后调用：那时 motor/encoder 已初始化完，
  *         且 printf 那句"初始化成功"已经打完，不会混进波形流。
  */
void PidTune_Init(void);

/**
  * @brief  控制节拍：10 ms 一次，由 TIM7 中断调用
  * @note   函数里每个电机每拍只读一次编码器（读一次就更新基准，读两次
  *         会把测速窗口切成两半）。所以本函数只能被 TIM7 以 100 Hz 调，
  *         绝不能在主循环里再调一次。
  */
void PidTune_Tick10ms(void);

/**
  * @brief  收命令并执行，主循环里反复调用，非阻塞
  */
void PidTune_Process(void);

/**
  * @brief  打开 VOFA 波形输出（上电默认是关的）
  * @note   为什么要有这个"闸"：TIM7 在 encoder_init() 里就启动了，比
  *         PidTune_Init() 和后面那几句启动日志都早。波形走
  *         HAL_UART_Transmit_IT，启动日志走阻塞 printf，两者抢同一个
  *         USART2->DR —— 日志会被截成半行、和波形数字粘在一起，
  *         "到底打到哪一步"就看不出来了。
  *         所以 main 里初始化全跑完、最后一句日志打完，再调本函数开闸。
  */
void PidTune_WaveEnable(void);

#endif
