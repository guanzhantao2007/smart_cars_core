#ifndef __YAW_LOOP_H
#define __YAW_LOOP_H

#include <stdint.h>
#include "pid.h"

/* ============================================================================
 * 几何常量区（物理事实：编译期定死，不放变量、不占 RAM、不许有第二份定义）
 * ========================================================================== */

/* 轮距 L = 左右轮「接地中心」之间的距离，单位 mm。
 *
 * 【实测记录 2026-11-22｜卷尺｜主理人本人测量，非推算、非"常见值"】
 *   前轴：D_out = 146 mm，D_in = 110 mm  →  L_front = (146+110)/2 = 128.0 mm
 *   后轴：D_out = 144 mm，D_in = 108 mm  →  L_rear  = (144+108)/2 = 126.0 mm
 *   |L_front − L_rear| = 2.0 mm，未超 2 mm 阈值 ⇒ 取平均
 *   L = (128.0 + 126.0)/2 = 127.0 mm
 *
 *   单位说明：主理人报的是 cm（14.6 / 11 / 14.4 / 10.8 / 12.8 / 12.6），
 *   此处一律 ×10 换成 mm。换算不是猜：12.8 mm 的轮距放在 235×140 mm 的车上
 *   物理不成立；且上面两条 (D_out+D_in)/2 与主理人报的 12.8 / 12.6 逐一自洽。
 *   前后差 2 mm 且**同向**（前轴外缘、内缘各多 2 mm），更像卷尺零点/前后轴
 *   装配的整体偏差，而不是车架菱形 —— 所以按规则取平均，不拒绝。
 *   离散度：主理人口述"量了两次，基本一样"，未报具体离散值。
 *
 * 【测量方法】外缘距 D_out（最外侧↔最外侧）与内缘距 D_in（两内侧面之间）
 *   取平均。推导：D_out = L + w、D_in = L − w（w = 胎宽）⇒ 平均恰为 L，
 *   **与胎宽无关** —— 所以这个方法只要求两次量在同一个基准宽度上。
 *   自检：(D_out − D_in)/2 = 18 mm，前后两轴一致 ⇒ 两次确实同一基准。
 *   （若实际胎宽不是 18 mm，说明有一侧量到了别的台阶面，L 会偏，需重量。）
 *
 * 【不要当"有效轮距"用】这是**几何**真值。实车转弯轮胎有侧滑，有效轮距通常
 *   比几何值大 5~15%。T07 若发现转向系统性偏小，那是侧滑，**不要回来改这个
 *   数** —— 改了物理就错了，且再也分不清"真值"与"补偿系数"各占多少。
 *
 * 【T07 差速分配用此 L 时必须转单位】
 *   差速公式 v_diff = ω·L 里 ω 的单位是 rad/s（量纲 (mm/s)/mm = 1/s），
 *   而 YawLoop_t.omega_dps 字段是 **deg/s**，两者差 π/180 ≈ 57.3 倍。正确写法：
 *       v_diff = omega_dps × (π/180) × YAW_TRACK_MM
 *               = omega_dps × 0.0174533f × YAW_TRACK_MM
 *   直接把 deg/s 乘进来，结果只有正确值的 1/57.3 —— 症状是"角度环几乎不动作、
 *   怎么加增益都没用"，而增益此时完全无辜，极易误判成"增益给太小"。
 * ========================================================================== */
#define YAW_TRACK_MM   127.0f

/* ============================================================================
 * 角度环骨架（第 1 步：只占位，不接线）
 *
 * 现在这里只有"形状"，没有"动作"：
 *   - YawLoop_t 把将来要用的字段摆好
 *   - 四个函数只做清零 / 赋值 / 返回；YawLoop_Tick 是空实现
 *   - 实例由 yaw_loop.c 内部以 static 持有，本头文件不暴露任何全局变量
 *   - 不调用 IMU_ / encoder_ / motor_ 的任何接口；也没有任何模块调用本模块
 *
 * 结论：编进固件，但运行时零影响。车的行为与加这个模块之前完全一致。
 *
 * 状态机（本轮只定义，不驱动）：
 *   YAW_OFF    未启用，角度环不参与控制
 *   YAW_ON     已启用
 *   YAW_ERROR  异常（例如 IMU 数据失效），判定条件留待后续任务定义
 * ========================================================================== */

/* 角度环状态 */
typedef enum
{
    YAW_OFF   = 0,   /* 未启用 */
    YAW_ON    = 1,   /* 已启用 */
    YAW_ERROR = 2    /* 异常   */
} YawLoop_State_t;

/* 角度环实例
 * 注：pid 是按值嵌入（不是指针），所以本头文件必须包含 pid.h，
 *     否则编译器算不出本结构体的布局。 */
typedef struct
{
    PID_t   pid;            /* 角度环 PID，本轮增益全 0，真值后续任务定 */
    float   target_deg;     /* 目标角度，单位 deg */
    float   measured_deg;   /* 实测角度，单位 deg（本轮不采集） */
    float   omega_dps;      /* 角速度，单位 deg/s（本轮不采集，留给阻尼/前馈） */
    uint8_t state;          /* 取值为 YawLoop_State_t，用 uint8_t 存便于整字节赋值 */

    /* 【T12b 新增｜到位锁存】0 = 还在追目标，1 = 已进入死区、输出被强制为 0。
     *   带滞环：进死区用 ±YAW_DONE_DEG(3°)，出死区要 ±YAW_RESUME_DEG(6°)。
     *   为什么需要它：原地转时，err 小到一定程度后单轮目标速度会掉到地面
     *   死区以下（实测 <25 mm/s 就带不动），轮子不动而速度环积分继续爬，
     *   实测 +7%/s，约 9 s 顶到 100% —— 这就是"长时间堵转磨电机"的来源。 */
    uint8_t done;
} YawLoop_t;

/* 对外接口
 * 注：开/关没有独立的字段，GetEnable() 就是 (state == YAW_ON) 的投影，
 *     保证 state 是唯一真值，不会出现"enable=1 而 state=ERROR"这种矛盾。 */
void            YawLoop_Init(void);
void            YawLoop_SetTarget(float target_deg);
YawLoop_State_t YawLoop_GetState(void);
void            YawLoop_Tick(void);

void            YawLoop_SetEnable(uint8_t on);   /* 非 0 = 开(YAW_ON)，0 = 关(YAW_OFF) */
float           YawLoop_GetTarget(void);         /* 目标角，deg */
uint8_t         YawLoop_GetEnable(void);         /* 1 = 已开，0 = 未开/异常 */

/* 读"到位"锁存（带滞环），1 = 已在目标 ±3° 内，ω 被强制为 0。
 *   调用点：pid_tune.c 的注入段 —— 到位时调 all_stop()，把目标清零并
 *   PID_Reset 四个速度环，避免积分继续往上爬（见 YawLoop_t.done 的注释）。
 *   置位条件：|err| < YAW_DONE_DEG(3°)；
 *   清除条件：|err| > YAW_RESUME_DEG(6°)，或 yawt 改目标，或 yawon 重新开环。
 *   滞环不可省：3° 进、3° 出会因 IMU 底噪在门限上来回翻，车一顿一顿地抽搐。 */
uint8_t         YawLoop_IsDone(void);

/* 读角度环当前输出 ω，单位 deg/s。正方向 = **使 yaw 增大的方向**。
 *   返回 0.0f 的三种情况：state 非 YAW_ON / IMU 未就绪 / 误差恰好为 0。
 *   注意它**只供观测**（波形 CH13），本轮没有任何电机吃这个值。 */
float           YawLoop_GetOmegaDps(void);

/* 读角度环输出限幅值 pid.OutMax，单位 deg/s。
 *   唯一用途：诊断 —— 确认 YawLoop_Init() 真的跑过。
 *   背景（2026-11-22 真踩过）：Init 没被调用时 s_yaw 落在 BSS 全 0，
 *   OutMax=0 会把 Tick 算出的 ω 一路压成 0，波形 CH13 恒 0，现象与
 *   "误差本来就是 0" 完全一样，只看 CH13 分不出来。
 *   判据：yaw 命令回显里 YOMX=250.0 ⇒ Init 生效；YOMX=0.0 ⇒ Init 没跑。
 *   （2026-11-22 由 100.0 提到 250.0，见 yaw_loop.c 的 YAW_KP_TEST 注释。） */
float           YawLoop_GetOutMax(void);

/* 读本拍采到的 yaw，单位 deg。
 *   用途：波形 CH9 与 CH12 都改读它，保证一帧内 CH9/CH12/CH13 是同一个样本。
 *   关键性质：Tick 里**无条件**刷新（先采样本、后判 state），所以 yawoff 时
 *   它照样跟着真实 yaw 走 —— 波形不会冻结成一条平线。
 *   若将来有人把"读 yaw"挪到判 state 之后，CH9 会在关环后冻住，
 *   现象酷似"IMU 停止更新"，所以这条性质不要改。 */
float           YawLoop_GetMeasuredDeg(void);

/* 最短路径角度误差（纯函数：不读全局、不碰硬件、无副作用）
 *   入参 target / actual 均为 deg，单位与 IMU_GetYawDeg() 一致
 *   返回   err ∈ (−180, 180]：> 0 表示需要增大 yaw（正面朝上安装时即逆时针）
 *   坏数据（NaN / ±∞）返回 0.0f
 * 手动注入和上层自动下发都调这一个函数，不许各写一套。 */
float           YawLoop_ErrorDeg(float target, float actual);

/* 差速分配（纯函数：不读全局、不碰硬件、无副作用、**不做限幅**）
 *
 *   out 顺序固定为 {左后, 右后, 右前, 左前}，与 pid_tune.c 的 s_target[0..3] 一一对应。
 *   依据：encoder.c:69-74 的电机编号 1=左后 / 2=右后 / 3=右前 / 4=左前，
 *         而 pid_tune.c 里 s_target[i] ↔ 电机 i+1。
 *   ⚠ 写成直觉顺序 {左前,右前,左后,右后} 编译不报错、也不会崩，只会在
 *     ω>0 时让车转反或四轮互相打架 —— 只能靠实物发现，所以别改这个顺序。
 *
 *   入参：
 *     v_mm_s     整车速度，mm/s。正值 = 车头方向（极性已在 motor.c:45/:164
 *                底层吸收，只有 2 号翻转，所以本函数**不许**再对输出取负号）
 *     omega_dps  角速度，deg/s。正 = 逆时针 → 右轮加速、左轮减速
 *                ⚠ 该方向依赖「MPU6050 正面朝上安装」，此前提 T08 需实物验证；
 *                  若实测反了，只在 half 前加负号，不要去改 imu.c
 *     track_mm   轮距，mm（传入 YAW_TRACK_MM）
 *     out        输出 4 个轮速目标，mm/s。形参里的 out[4] 会退化为指针，
 *                长度靠本注释约定，编译器不检查越界。
 *
 *   【不做限幅，是故意的】超过 ±MOTOR_PWM_FULL_SCALE_MM_S(1657) 的值原样输出，
 *   由最底层 speed2pluse() 饱和到满占空比 —— 所以不会溢出，只会饱和。
 *   抗积分饱和（windup）属 T10 注入层的事，不许在这里偷偷夹。
 *
 *   【坏数据】ω 或 v 任一是 NaN / ±∞，四路输出全置 0（当"停车"处理），
 *   理由：NaN 一旦穿进 PID 的积分器就永久是 NaN，之后每拍输出都是垃圾。 */
void            YawLoop_DiffDrive(float v_mm_s, float omega_dps,
                                  float track_mm, float out[4]);

#endif /* __YAW_LOOP_H */
