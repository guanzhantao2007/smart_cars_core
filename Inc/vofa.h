#ifndef __VOFA_H
#define __VOFA_H

#include <stdint.h>

/*
 * VOFA+ 波形发送封装（FireWater 文本协议）
 *
 * 【这一层只管什么】
 *   把一串整数排成 "v0,v1,v2\n" 然后交给 serial.c 发出去。
 *   它**不知道**每个数是目标还是实际、是左轮还是右轮 —— 那是调用方的事。
 *   这样以后改协议（加通道、乘 10 提高分辨率、换 justfloat 二进制、
 *   加帧头）都只动 vofa.c，不用在 1284 行的 main.c 里翻。
 *
 * 【为什么不在这里读全局变量】
 *   如果让 vofa.c 自己去读 target1/act1，就得持有 volatile float*，
 *   在中断里通过指针解引用：指针本身不是 volatile 时，编译器可能把它
 *   缓存进寄存器，读到的是旧值 —— 这种 bug 只在 -O2 下偶发，极难查。
 *   传数组虽然多写两行，但数据流向是看得见的。
 *
 * 【调用约束】
 *   只在中断上下文调用（Control_Tick 的 40ms 分支）。
 *   函数内部不阻塞、不做浮点格式化、不碰任何 HAL 等待接口。
 */

/* 一帧最多几列。VOFA 的 FireWater 按逗号数认列，列数必须每帧恒定，
   所以这里的上限只决定缓冲区大小，不代表"想发几列就发几列"。
   2026-11-22：pid_tune 的波形从 5 列（目标+四路速度）扩到 9 列
   （再加四路输出占空比），上限随之 8 → 10，缓冲 98 → 122 字节。
   留一列余量是为了以后再加"目标vs反馈误差"时不必再动这个宏。 */
/* 【2026-11-22 P0 改】10 -> 13：给 yaw / gz 留位置（本工程现用 11 列）。
 * 这个宏只管"最多允许几列"，帧里的列数由 pid_tune.c 的 TUNE_WAVE_CH 决定，
 * 两处必须满足 TUNE_WAVE_CH <= VOFA_MAX_CH，否则 VOFA_SendFix1 会静默
 * 拒发整帧（表现为"波形突然没了"）。
 * 缓冲区是按本宏开的：13*12+2 = 158 字节，够 11 列的最坏情况（134 字节）。 */
/* 【2026-11-22 角度环观测改】13 -> 16：波形 11 -> 14 列，追加
 * CH11 角度目标 / CH12 角度误差 / CH13 ω 输出（本轮恒 0）。
 * 仍留 2 列余量（T09 接差速时还要再加），所以直接开到 16 而不是刚好的 14。
 * 缓冲：16*12+2 = 194 字节，够 14 列最坏 112 字节（每列 ≤7 字符 + 13 逗号 + '\n'）。
 *
 * 【三处尺寸必须一起改，缺一个就翻车】
 *   TUNE_WAVE_CH(14) <= VOFA_MAX_CH(16)   本宏，决定"允不允许发"+拼帧缓冲
 *   TX_BUF_SIZE(128) > 实际最坏帧长(112)  serial_async.c，决定"搬不搬得完"
 * 只改列数：n > VOFA_MAX_CH 直接 return，整帧静默丢 → 图上空白。
 * 只改本宏：帧仍被 96 截断 → 丢掉行尾 '\n'，与下一帧粘连 → 图长时间不动。 */
#define VOFA_MAX_CH   16U

/**
  * @brief  把 n 个整数按 FireWater 文本协议发出去
  * @param  v 整数数组，v[0] → CH0，v[1] → CH1 …
  * @param  n 列数，1 ~ VOFA_MAX_CH
  * @retval 无
  * @note   n 非法（0 或超上限）时静默返回，不报错 ——
  *         这里在中断里，发不出一帧比打断时序安全。
  */
void VOFA_SendInts(const int32_t *v, uint8_t n);

/**
  * @brief  一位小数版：入参是「乘 10 后的整数」，输出 "30.5" 这种字符串
  * @param  v10 每列的实际值乘 10（例：30.5 mm/s 传 305）
  * @param  n   列数，1 ~ VOFA_MAX_CH，每帧必须恒定
  * @note   为什么不用 %f：本工程用 AC5，sprintf 不支持浮点格式，用了会拖进
  *         整套软件浮点库（几 KB）且打印出乱码。这里用整数除/模拼小数点，
  *         字节数和不带小数时几乎一样。
  *         速度量的变化幅度小（0~100 mm/s），整数刻度看不出稳态纹波，
  *         所以波形统一用这个版本，纵轴读数除以 10 就是 mm/s。
  */
void VOFA_SendFix1(const int32_t *v10, uint8_t n);

#endif
